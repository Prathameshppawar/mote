pub fn hindi_weight(lowercase: &str) -> f32 {
    static INDEX: OnceLock<HashMap<&'static str, f32>> = OnceLock::new();
    INDEX.get_or_init(|| index(HINDI_LATIN)).get(lowercase).copied().unwrap_or(0.0)
}

/// Weight of `lowercase` in the Marathi lexicon (0.0 when absent).
pub fn marathi_weight(lowercase: &str) -> f32 {
    static INDEX: OnceLock<HashMap<&'static str, f32>> = OnceLock::new();
    INDEX.get_or_init(|| index(MARATHI_LATIN)).get(lowercase).copied().unwrap_or(0.0)
}

/// Whether `lowercase` is a recognisable romanized Hindi or Marathi word that is
/// not also a common English word. Spelling correction skips such tokens.
pub fn is_indic_word(lowercase: &str) -> bool {
    hindi_weight(lowercase) >= 0.3 || marathi_weight(lowercase) >= 0.3
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn lexicons_are_lowercase_and_unique() {
        for table in [HINDI_LATIN, MARATHI_LATIN] {
            let mut seen = HashSet::new();
            for (word, weight) in table {
                assert_eq!(*word, word.to_lowercase(), "{word} must be lowercase");
                assert!((0.0..=1.0).contains(weight), "{word} weight out of range");
                assert!(seen.insert(*word), "duplicate lexicon entry: {word}");
            }
        }
    }

    #[test]
    fn common_english_words_are_weak() {
        for w in ["to", "the", "is", "us", "me", "are", "he", "hi", "do"] {
            assert!(hindi_weight(w) < 0.2 && marathi_weight(w) < 0.2, "{w} must be weak");
        }
    }

    #[test]
    fn distinctive_words_are_strong() {
        assert_eq!(hindi_weight("hai"), 1.0);
        assert_eq!(marathi_weight("aahe"), 1.0);
        assert!(is_indic_word("karaycha"));
        assert!(!is_indic_word("deployment"));
    }
}
